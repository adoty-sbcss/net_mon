def empty_baseline() -> dict[str, Any]:
    return {"updated_at": None, "sample_count": 0, "modes": {}}


def merge_baseline(
    baseline: dict[str, Any], traces: list[dict[str, Any]]
) -> dict[str, Any]:
    """Fold healthy traces into the baseline, accumulating per-hop IP SETS.

    ECMP is absorbed here rather than in the probe. A hop that load-balances
    accrues its handful of alternatives over successive samples and thereafter
    matches any of them; a genuinely stable hop keeps exactly one address, so a
    substitution there stays a real signal. This is why one sample is not a
    baseline: on the measured path, hops 5 and 10 flap and would otherwise
    report a divergence on every single healthy run.
    """
    out: dict[str, Any] = {
        "updated_at": _now_iso(),
        "sample_count": int(baseline.get("sample_count") or 0),
        "modes": dict(baseline.get("modes") or {}),
    }
    for tr in traces:
        if tr.get("error") or not tr.get("hops"):
            continue
        mode = str(tr.get("mode"))
        entry = dict(out["modes"].get(mode) or {})
        # If the destination changed, the accumulated hops describe a path to
        # somewhere else. Merging into them would build a chimera — `dest` naming
        # the new target while `hop_ips` and `deepest_responding_hop` still hold
        # the old route — which then PASSES compare()'s destination check and
        # reports the difference between two unrelated paths as a break. Start
        # this mode's baseline over instead.
        if entry.get("dest") and entry["dest"] != tr.get("dest"):
            log.info("wan-path baseline reset: destination changed",
                     mode=mode, was=entry["dest"], now=tr.get("dest"))
            entry = {}
        entry["dest"] = tr.get("dest")
        hop_ips: dict[str, list[str]] = {
            str(k): list(v) for k, v in (entry.get("hop_ips") or {}).items()
        }
        for h in tr["hops"]:
            ip = h.get("ip")
            if not ip:
                continue
            key = str(h["hop"])
            seen = hop_ips.setdefault(key, [])
            if ip not in seen:
                seen.append(ip)
        entry["hop_ips"] = hop_ips
        # The deepest hop that has EVER answered. A capture that stops well short
        # of this is the finding; one that matches it is a normal end-of-path.
        deepest = max((int(k) for k in hop_ips), default=0)
        entry["deepest_responding_hop"] = max(
            int(entry.get("deepest_responding_hop") or 0), deepest
        )
        if tr.get("reached_at"):
            entry["reached_at"] = tr["reached_at"]
        out["modes"][mode] = entry
        out["sample_count"] += 1
    return out


def compare(baseline: dict[str, Any], tr: dict[str, Any]) -> dict[str, Any]:
    """Diff one trace against the baseline for its mode.

    Reports two distinct things, because they mean different things to an
    engineer: the path STOPPING EARLY (a break), and a hop being SUBSTITUTED (a
    reroute). Only the first is an outage signature.
    """
    mode = str(tr.get("mode"))
    entry = (baseline.get("modes") or {}).get(mode)
    # A baseline is only meaningful for the destination it was measured against.
    # Change `wan_path_targets` and the stored path is a path to somewhere else —
    # comparing against it manufactures a break out of a shorter route. Caught on
    # a live sensor: a capture aimed one hop away was headlined "the path stops
    # after hop 1" purely because the baseline had been built to 1.1.1.1, eleven
    # hops out. Fail closed and claim nothing until the baseline is rebuilt.
    if entry and entry.get("dest") and tr.get("dest") and entry["dest"] != tr["dest"]:
        entry = None
    if not entry:
        return {"mode": mode, "have_baseline": False, "short_by": None,
                "break_after_hop": None, "break_after_ip": None, "new_ips": []}

    hop_ips: dict[str, list[str]] = entry.get("hop_ips") or {}
    new_ips: list[dict[str, Any]] = []
    for h in tr.get("hops") or []:
        ip = h.get("ip")
        if not ip:
            continue
        known = hop_ips.get(str(h["hop"])) or []
        if known and ip not in known:
            new_ips.append({"hop": h["hop"], "ip": ip, "baseline": known})

    deepest_known = int(entry.get("deepest_responding_hop") or 0)
    last = tr.get("last_responding_hop")
    last_int = int(last) if last else 0
    # A trace that REACHED its destination did not break, however deep the
    # baseline happens to go. Without this, a route that legitimately shortened
    # (a closer anycast node, a restored direct path) reads as a failure — the
    # measurement arriving is the strongest possible evidence that it did not.
    if tr.get("reached_at"):
        short_by = None
    else:
        short_by = deepest_known - last_int if deepest_known > last_int else None

    break_after_ip = None
    if short_by:
        break_after_ip = next(
            (h.get("ip") for h in (tr.get("hops") or []) if h.get("hop") == last_int),
            None,
        )
    return {
        "mode": mode,
        "have_baseline": True,
        "baseline_deepest_hop": deepest_known,
        "short_by": short_by,
        "break_after_hop": last_int if short_by else None,
        "break_after_ip": break_after_ip,
        "new_ips": new_ips,
    }


