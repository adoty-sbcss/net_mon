# Verdict codes, most specific first. These are the operator-facing conclusions;
# each is a claim we can actually support from the measurements above.
VERDICT_OK = "ok"
VERDICT_LAN = "lan"
VERDICT_DNS = "dns"
VERDICT_TCP_BLOCKED = "tcp_blocked"
VERDICT_WAN_DOWN = "wan_down"
VERDICT_DASHBOARD_ONLY = "dashboard_only"

_VERDICT_TEXT = {
    VERDICT_OK: "the path is healthy from here",
    VERDICT_LAN: "the sensor's own gateway is not answering - this is a LAN-side "
                 "fault, and nothing beyond it can be diagnosed from this box",
    VERDICT_DNS: "name resolution is failing while direct IP connections still "
                 "work - the circuit is up, the resolver is not",
    VERDICT_TCP_BLOCKED: "ICMP crosses the path but NO new TCP session to :443 "
                         "completes - the signature of a stateful device dropping "
                         "new sessions (state table, licence, or policy), not a "
                         "dead circuit",
    VERDICT_WAN_DOWN: "no path to the internet: neither ICMP nor TCP reaches any "
                      "control target, while the local gateway still answers",
    VERDICT_DASHBOARD_ONLY: "the internet is reachable but the dashboard is not - "
                            "this is a dashboard-side or DNS-side fault, NOT a "
                            "site outage",
}


def decide(
    gateway: dict[str, Any] | None,
    controls: list[dict[str, Any]],
    dashboard_control: dict[str, Any] | None,
    dns: dict[str, Any] | None,
    icmp_internet_ok: bool,
) -> dict[str, Any]:
    """Turn the measurements into one supportable conclusion.

    Ordered most-specific first so a LAN fault is never reported as a WAN
    outage, and a dashboard outage is never reported as a site outage — that
    misattribution is the whole reason this exists.
    """
    if gateway is not None and not gateway.get("alive"):
        code = VERDICT_LAN
    elif controls and all(not c.get("ok") for c in controls):
        # Every independent internet control refused a new TCP session.
        code = VERDICT_TCP_BLOCKED if icmp_internet_ok else VERDICT_WAN_DOWN
    elif dns is not None and not dns.get("ok"):
        # IP literals connected (we are past the all-fail branch) but names do not
        # resolve. Distinct fault, distinct owner.
        code = VERDICT_DNS
    elif dashboard_control is not None and not dashboard_control.get("ok"):
        code = VERDICT_DASHBOARD_ONLY
    else:
        code = VERDICT_OK
    return {"code": code, "summary": _VERDICT_TEXT[code]}


def capture(
    *,
    reason: str,
    controls: list[str],
    dashboard_host: str | None = None,
    gateway_ip: str | None = None,
    dns_name: str = "cloudflare.com",
    trace_dest: str | None = None,
    baseline: dict[str, Any] | None = None,
    budget_sec: int = CAPTURE_BUDGET_SEC,
) -> dict[str, Any]:
    """Run the bounded evidence ladder and return one capture record.

    `controls` are IP LITERALS from validated config — never names, so a dead
    resolver cannot be mistaken for a dead circuit, and never caller argv.
    """
    started_mono = time.monotonic()
    rec: dict[str, Any] = {
        "startedAt": _now_iso(),
        "reason": reason,
        "gateway": None,
        "dns": None,
        "controls": [],
        "dashboardControl": None,
        "icmpInternetOk": False,
        "traces": [],
        "diffs": [],
        "verdict": None,
        "truncated": False,
        "elapsedMs": 0,
    }

    def _left() -> float:
        return budget_sec - (time.monotonic() - started_mono)

    if gateway_ip:
        rec["gateway"] = ping(gateway_ip)

    # TCP controls first: they are fast and they carry the verdict.
    for target in controls:
        rec["controls"].append(tcp_connect(target, 443))
    if dashboard_host:
        rec["dashboardControl"] = tcp_connect(dashboard_host, 443)

    rec["dns"] = dns_resolves(dns_name)

    # Does ICMP cross where TCP did not? This is the divergence that separates a
    # stateful-firewall failure from a dead circuit, and it is measured at the
    # CONNECT level (reliable) rather than read off traceroute (noisy).
    icmp_ok = False
    for target in controls:
        if _left() <= 0:
            rec["truncated"] = True
            break
        if ping(target, count=2, timeout=2).get("alive"):
            icmp_ok = True
            break
    rec["icmpInternetOk"] = icmp_ok

    dest = trace_dest or (controls[0] if controls else None)
    if dest:
        for mode in ("icmp", "tcp443"):
            # Each trace can cost ~max_hops*wait in the blackout case. Only start
            # one we can afford to finish; a partial capture beats a killed one.
            if _left() < TRACE_TIMEOUT_SEC:
                rec["truncated"] = True
                break
            tr = trace(dest, mode)
            rec["traces"].append(tr)
            if baseline:
                rec["diffs"].append(compare(baseline, tr))

    rec["verdict"] = decide(
        rec["gateway"], rec["controls"], rec["dashboardControl"],
        rec["dns"], icmp_ok,
    )
    # Attach the hop bracket to the verdict when the diff supports one, so the
    # headline can say WHERE without the reader assembling it.
    brk = next((d for d in rec["diffs"] if d.get("break_after_ip")), None)
    if brk:
        rec["verdict"]["breakAfterHop"] = brk["break_after_hop"]
        rec["verdict"]["breakAfterIp"] = brk["break_after_ip"]
    rec["elapsedMs"] = int((time.monotonic() - started_mono) * 1000)
    return rec


