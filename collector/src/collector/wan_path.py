def _write_json(path: Path, doc: Any) -> None:
    """Atomic write — a partial file must never be read back as truth."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(json.dumps(doc, indent=2), encoding="utf-8")
    tmp.replace(path)


def _read_json(path: Path, default: Any) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001 — missing/corrupt state is not fatal
        return default


def load_baseline() -> dict[str, Any]:
    doc = _read_json(BASELINE_FILE, None)
    return doc if isinstance(doc, dict) else empty_baseline()


def save_baseline(doc: dict[str, Any]) -> None:
    _write_json(BASELINE_FILE, doc)


def load_state() -> dict[str, Any]:
    doc = _read_json(STATE_FILE, None)
    return doc if isinstance(doc, dict) else {}


def save_state(doc: dict[str, Any]) -> None:
    _write_json(STATE_FILE, doc)


def save_capture(rec: dict[str, Any]) -> Path:
    """Persist a capture, evicting the OLDEST beyond the cap."""
    CAPTURE_DIR.mkdir(parents=True, exist_ok=True)
    existing = sorted(CAPTURE_DIR.glob("*.json"))
    for stale in existing[: max(0, len(existing) + 1 - CAPTURE_MAX)]:
        stale.unlink(missing_ok=True)
    path = CAPTURE_DIR / f"{time.time_ns():020d}.json"
    _write_json(path, rec)
    return path


def recent_captures(limit: int = 5) -> list[dict[str, Any]]:
    """Newest-first."""
    try:
        files = sorted(CAPTURE_DIR.glob("*.json"), reverse=True)[:limit]
    except Exception:  # noqa: BLE001
        return []
    out: list[dict[str, Any]] = []
    for f in files:
        doc = _read_json(f, None)
        if isinstance(doc, dict):
            out.append(doc)
    return out


# ---------------------------------------------------------------------------
# Rendering — an engineer reads a hop table, not raw command output
# ---------------------------------------------------------------------------


def render(rec: dict[str, Any], baseline: dict[str, Any] | None = None) -> str:
    """Render one capture as a hop table with a verdict and a baseline diff."""
    lines: list[str] = []
    v = rec.get("verdict") or {}
    lines.append(f"WAN PATH  {rec.get('startedAt')}  (reason: {rec.get('reason')})")
    head = f"VERDICT: {v.get('code', '?')} - {v.get('summary', '')}"
    if v.get("breakAfterIp"):
        head += (f"\n         the path stops after hop {v['breakAfterHop']} "
                 f"({v['breakAfterIp']}); the baseline gets further")
    lines.append(head)
    if rec.get("truncated"):
        lines.append("NOTE: capture hit its time budget - some probes were skipped")
    lines.append("")

    gw = rec.get("gateway")
    if gw:
        state = "alive" if gw.get("alive") else "NO REPLY"
        lines.append(f"  gateway  {gw.get('target', ''):<22} {state:<9} "
                     f"loss {gw.get('loss_pct')}%")
    dns = rec.get("dns")
    if dns:
        lines.append(f"  dns      {dns.get('name', ''):<22} "
                     f"{'ok' if dns.get('ok') else 'FAIL':<9} {dns.get('error') or ''}")
    for c in rec.get("controls") or []:
        lines.append(f"  tcp/443  {c.get('target', ''):<22} "
                     f"{'ok' if c.get('ok') else 'FAIL':<9} {c.get('error') or ''}")
    dc = rec.get("dashboardControl")
    if dc:
        lines.append(f"  tcp/443  {dc.get('target', ''):<22} "
                     f"{'ok' if dc.get('ok') else 'FAIL':<9} "
                     f"{dc.get('error') or ''}  (dashboard)")
    lines.append(f"  icmp to internet: {'yes' if rec.get('icmpInternetOk') else 'NO'}")
    lines.append("")

    base = baseline or {}
    by_mode = {str(t.get("mode")): t for t in (rec.get("traces") or [])}
    if by_mode:
        lines.append(f"  {'hop':>3}  {'icmp':<22} {'tcp/443':<22} baseline")
        max_hop = max(
            (h["hop"] for t in by_mode.values() for h in (t.get("hops") or [])),
            default=0,
        )
        base_icmp = ((base.get("modes") or {}).get("icmp") or {}).get("hop_ips") or {}
        for n in range(1, max_hop + 1):
            cells = []
            for mode in ("icmp", "tcp443"):
                t = by_mode.get(mode)
                hop = next(
                    (h for h in ((t or {}).get("hops") or []) if h["hop"] == n), None
                )
                if hop is None:
                    cells.append("")
                elif hop.get("ip"):
                    cells.append(f"{hop['ip']} {hop.get('rtt_ms')}ms")
                else:
                    cells.append("*")
            known = base_icmp.get(str(n)) or []
            marker = ""
            if v.get("breakAfterHop") == n:
                marker = "  <- PATH ENDS HERE"
            lines.append(f"  {n:>3}  {cells[0]:<22} {cells[1]:<22} "
                         f"{'|'.join(known)}{marker}")
    for d in rec.get("diffs") or []:
        for n in d.get("new_ips") or []:
            lines.append(f"  note: {d['mode']} hop {n['hop']} is {n['ip']}, "
                         f"baseline saw {'|'.join(n['baseline'])} (reroute)")
    if not (base.get("modes") or {}):
        lines.append("")
        lines.append("  NOTE: no baseline captured yet - stars below are not "
                     "interpretable until this site has a known-good path on file.")
    return "\n".join(lines)
