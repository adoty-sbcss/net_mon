"""WAN-path evidence: name the hop where the path broke (PERF-7).

A district lost its internet over roughly a week and NetMon never said what
broke. The signal that looked like proof — ~47% of speed tests returning
0.0 Mbps — turned out to be Cloudflare rate-limiting our own probe (three
sensors behind one egress IP, HTTP 429). After PERF-2's honesty fix removed
that false signal, nothing remained that explained the outage.

This module captures the evidence that does: a bounded ladder run ON the sensor,
autonomously, at the moment the path is broken. It answers three questions in
order, and is careful about which of them it can actually answer:

  1. Is the sensor's own LAN alive?      (gateway ping)
  2. Can we open a NEW TCP session out?  (connect to :443 — the authoritative fact)
  3. Where does the path stop?           (traceroute, ICMP + TCP, vs a baseline)

WHY A TCP CONNECT IS THE VERDICT AND TRACEROUTE IS ONLY CORROBORATION
---------------------------------------------------------------------
A ping-based trigger misreads the case this exists for. In the stateful-firewall
failure, ICMP keeps flowing while NEW TCP sessions die — ping says "fine" while
every user says "the internet is down". So the verdict is driven by whether a
TCP handshake to :443 completes. That is binary, fast, and unambiguous.

Traceroute cannot carry the verdict, because on a real school network it lies in
both directions. Measured on a HEALTHY production sensor (Monitor1, 2026-09-05):

  * `traceroute -T -p 443 --sport=33434 1.1.1.1` — the fixed-flow form, which is
    the textbook recommendation for stable ECMP — returned hops 1-3 then STARS to
    the limit, taking 18s. Byte-identical to a genuinely unroutable address.
    Meanwhile a plain TCP connect to 1.1.1.1:443 succeeded in 15ms. Pinning the
    source port makes every probe one 5-tuple, and the on-path stateful device
    treats the repeated low-TTL SYNs as retransmits of a single half-open flow
    and stops eliciting replies. So the "fixed flow" advice inverts here: it
    manufactures a total-blackout reading on a perfectly healthy path.
  * Without `--sport`, the same trace mapped all 11 hops in 0.06s.

Hence: NO `--sport`. The ECMP instability that `--sport` is meant to solve is
real but small and LOCALISED — across four consecutive healthy runs, hops 1-4
and 6-9 were byte-identical every time; only hop 5 (CENIC) and hop 10
(Cloudflare) flapped between a handful of addresses. So we absorb ECMP in the
BASELINE instead of in the probe: the baseline records, per hop index, the SET of
addresses ever seen there. A hop that flaps accumulates its alternatives and
stops being interesting; a hop that is genuinely stable keeps exactly one.

WHAT THE HOP TABLE DOES AND DOESN'T PROVE
-----------------------------------------
For a failing edge device the hops bracket the break to "between our inside
interface and the first ISP hop" — they corroborate, they do not conclude. Two
rules keep it honest:

  * A star followed by a LATER responding hop is an artifact, not a break:
    routers rate-limit ICMP generated by their own control plane. Only a
    TRAILING run of stars marks where the path stops (`last_responding_hop`).
  * A path that ends in stars is only a FINDING when the baseline for this site
    got further. Plenty of healthy paths end in stars (the last hop before the
    dashboard does, in production). Without a baseline the reading is noise,
    which is why the baseline is load-bearing here rather than a refinement.

Everything is bounded: per-probe timeouts, a hop cap, and a wall-clock ceiling
that abandons remaining traces rather than overrunning. Nothing here takes
caller-supplied arguments — targets come from validated pushed config — so the
sensor's fixed-argv containment model is preserved.
"""
