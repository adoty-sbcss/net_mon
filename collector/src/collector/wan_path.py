def _trace_argv(dest: str, mode: str, max_hops: int, wait: int) -> list[str]:
    """Build the traceroute argv for a mode.

    NOTE the deliberate absence of `--sport`. See the module docstring: on a
    measured production path, pinning the source port turned a healthy 11-hop
    trace into hops 1-3 plus stars, in 18 seconds instead of 0.06.
    """
    argv = ["traceroute", "-n", "-m", str(max_hops), "-w", str(wait), "-q", "1"]
    if mode == "icmp":
        argv.append("-I")
    elif mode == "tcp443":
        argv += ["-T", "-p", "443"]
    else:  # pragma: no cover - guarded by the caller's fixed mode list
        raise ValueError(f"unknown traceroute mode {mode!r}")
    argv.append(dest)
    return argv


def trace(
    dest: str,
    mode: str = "icmp",
    *,
    max_hops: int = TRACE_MAX_HOPS,
    wait: int = TRACE_WAIT_SEC,
) -> dict[str, Any]:
    """Run one traceroute. Returns a structured path; never raises."""
    if not shutil.which("traceroute"):
        return {"mode": mode, "dest": dest, "hops": [], "reached_at": None,
                "last_responding_hop": None, "error": "traceroute not installed"}
    try:
        res = subprocess.run(
            _trace_argv(dest, mode, max_hops, wait),
            capture_output=True, text=True, timeout=TRACE_TIMEOUT_SEC, check=False,
        )
    except subprocess.TimeoutExpired:
        return {"mode": mode, "dest": dest, "hops": [], "reached_at": None,
                "last_responding_hop": None, "error": "traceroute timed out"}
    except (FileNotFoundError, OSError) as exc:
        return {"mode": mode, "dest": dest, "hops": [], "reached_at": None,
                "last_responding_hop": None, "error": str(exc)[:200]}

    hops = _parse_hops(res.stdout or "")
    reached_at = next((h["hop"] for h in hops if h["ip"] == dest), None)
    return {
        "mode": mode,
        "dest": dest,
        "hops": hops,
        "reached_at": reached_at,
        "last_responding_hop": last_responding_hop(hops),
        "error": None,
    }


def _parse_hops(stdout: str) -> list[dict[str, Any]]:
    """Parse traceroute -n output into [{hop, ip, rtt_ms}] (ip None for a star)."""
    hops: list[dict[str, Any]] = []
    for line in stdout.splitlines():
        m = _HOP_LINE.match(line)
        if not m:
            continue  # the "traceroute to ..." header
        rest = m.group(2)
        ipm = _IPV4.search(rest)
        msm = _FLOAT_MS.search(rest)
        rtt: float | None = None
        if msm:
            try:
                rtt = float(msm.group(1))
            except ValueError:
                rtt = None
        hops.append({"hop": int(m.group(1)),
                     "ip": ipm.group(1) if ipm else None,
                     "rtt_ms": rtt})
    return hops


def last_responding_hop(hops: list[dict[str, Any]]) -> int | None:
    """The last hop that answered, ignoring gaps that later hops close.

    Routers police ICMP generated by their own control plane, so an isolated
    star at hop k with a live hop k+1 says nothing about the path — hop k simply
    declined to speak. Only a run of stars extending to the END of the trace
    marks where forwarding actually stopped. Returns None if nothing answered.
    """
    last: int | None = None
    for h in hops:
        if h.get("ip"):
            last = h["hop"]
    return last


def trailing_star_count(hops: list[dict[str, Any]]) -> int:
    """How many consecutive non-answering hops close the trace."""
    n = 0
    for h in reversed(hops):
        if h.get("ip"):
            break
        n += 1
    return n


