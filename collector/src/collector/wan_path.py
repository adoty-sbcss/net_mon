def targets_from(settings: Any) -> list[str]:
    """Parse the configured control targets, keeping only IP LITERALS.

    Two reasons this is a hard filter and not a nicety:
      * The first target is passed to `traceroute` as its destination argument,
        and traceroute parses options wherever they appear — so a pushed value
        like "--help", or anything leading with '-', would become an OPTION
        rather than a destination. An `ip_address()` parse makes that
        structurally impossible, which is stronger than a character blocklist
        (the failure mode a previous fix on this box already had to unlearn:
        `splitlines()` splits on ten characters, not the three you thought of).
      * A control target that needed DNS could not distinguish a dead resolver
        from a dead circuit — a distinction this feature exists to make.
    """
    import ipaddress

    out: list[str] = []
    for raw in str(getattr(settings, "wan_path_targets", "") or "").split(","):
        cand = raw.strip()
        if not cand:
            continue
        try:
            ipaddress.ip_address(cand)
        except ValueError:
            log.warning("wan-path target is not an IP literal; ignoring", target=cand)
            continue
        if cand not in out:
            out.append(cand)
    return out


def tcp_connect(host: str, port: int = 443, timeout: float = 5.0) -> dict[str, Any]:
    """Open and immediately close a TCP session. Returns {ok, ms, error}.

    This is the control the whole ladder turns on, so it deliberately measures
    the HANDSHAKE and nothing above it. We do not send an HTTP request: an
    application-layer answer of ANY kind (200, 403, and notably 429 — the
    rate-limit that produced eight days of phantom evidence) already proves the
    path works, so folding HTTP in could only add ways to misread a working path
    as a broken one. A completed three-way handshake is the fact we want.
    """
    started = time.monotonic()
    try:
        with socket.create_connection((host, port), timeout=timeout):
            pass
    except OSError as exc:
        # strerror alone is often empty for timeouts; str(exc) carries the reason.
        return {
            "target": host,
            "port": port,
            "ok": False,
            "ms": round((time.monotonic() - started) * 1000, 1),
            "error": str(exc)[:200] or exc.__class__.__name__,
        }
    return {
        "target": host,
        "port": port,
        "ok": True,
        "ms": round((time.monotonic() - started) * 1000, 1),
        "error": None,
    }


def dns_resolves(name: str, timeout: float = 5.0) -> dict[str, Any]:
    """Resolve a name to prove the resolver works.

    Kept separate from the TCP controls, which use IP literals precisely so that
    a dead resolver cannot masquerade as a dead WAN. If the literals connect and
    this fails, the finding is DNS, not the circuit.
    """
    started = time.monotonic()
    prior = socket.getdefaulttimeout()
    try:
        socket.setdefaulttimeout(timeout)
        socket.getaddrinfo(name, 443, proto=socket.IPPROTO_TCP)
    except OSError as exc:
        return {"name": name, "ok": False,
                "ms": round((time.monotonic() - started) * 1000, 1),
                "error": str(exc)[:200] or exc.__class__.__name__}
    finally:
        socket.setdefaulttimeout(prior)
    return {"name": name, "ok": True,
            "ms": round((time.monotonic() - started) * 1000, 1), "error": None}


def ping(host: str, count: int = 3, timeout: int = 2) -> dict[str, Any]:
    """Small ICMP sample. Best-effort; never raises."""
    cmd = ["ping", "-n", "-c", str(count), "-W", str(timeout), host]
    try:
        res = subprocess.run(
            cmd, capture_output=True, text=True, timeout=count * timeout + 5, check=False
        )
    except (FileNotFoundError, subprocess.TimeoutExpired, OSError) as exc:
        return {"target": host, "alive": False, "rtt_ms": None, "loss_pct": 100.0,
                "error": str(exc)[:200] or "ping failed"}
    text = (res.stdout or "") + (res.stderr or "")
    loss: float | None = None
    m = _LOSS.search(text)
    if m:
        try:
            loss = float(m.group(1))
        except ValueError:
            loss = None
    rtt: float | None = None
    m = _RTT_AVG.search(text)
    if m:
        try:
            rtt = float(m.group(1))
        except ValueError:
            rtt = None
    alive = res.returncode == 0 or (loss is not None and loss < 100)
    return {"target": host, "alive": alive, "rtt_ms": rtt,
            "loss_pct": loss if loss is not None else (0.0 if alive else 100.0),
            "error": None if alive else "no reply"}


